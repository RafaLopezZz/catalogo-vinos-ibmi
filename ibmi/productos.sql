CREATE OR REPLACE PROCEDURE RAFALOPEZ1.ACTUALIZAR_STOCK
  (IN P_ID INTEGER, IN P_CANT INTEGER)
  LANGUAGE RPGLE
  EXTERNAL NAME 'RAFALOPEZ1/ACTSTOCK'
  PARAMETER STYLE GENERAL;

-- Llamarlo: restar 5 unidades al producto 1
