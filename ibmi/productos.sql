  ID      INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NOMBRE  VARCHAR(60) NOT NULL,
  TIPO    VARCHAR(20),
  PRECIO  DECIMAL(7,2),
  STOCK   INTEGER
);

